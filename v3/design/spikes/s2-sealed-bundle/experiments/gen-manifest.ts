// Build-time codegen: glob dist/ and emit a manifest module with one static
// `with { type: "file" }` import per asset. Bun's bundler has no import.meta.glob,
// so this generated module is how a *directory* of hashed files gets embedded.
// Run: bun gen-manifest.ts   (before every `bun build --compile`)
import { Glob } from "bun";

const dist = new URL("./dist/", import.meta.url).pathname;
const files = [...new Glob("**/*").scanSync({ cwd: dist, onlyFiles: true })].sort();

let out = `// AUTO-GENERATED by gen-manifest.ts — do not edit.\n`;
files.forEach((f, i) => {
  out += `import a${i} from ${JSON.stringify("./dist/" + f)} with { type: "file" };\n`;
});
out += `\nexport const manifest: Record<string, string> = {\n`;
files.forEach((f, i) => {
  out += `  ${JSON.stringify("/" + f)}: a${i},\n`;
});
out += `};\n`;

await Bun.write(new URL("./manifest.generated.ts", import.meta.url).pathname, out);
console.log(`manifest.generated.ts: ${files.length} assets`);
